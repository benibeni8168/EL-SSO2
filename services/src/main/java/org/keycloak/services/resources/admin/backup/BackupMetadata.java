package org.keycloak.services.resources.admin.backup;

import java.util.List;

/**
 * Metadata about a backup - returned to frontend for display.
 */
public class BackupMetadata {

    private String backupId;
    private String description;
    private long createdAt;             // epoch millis for easy JS handling
    private String createdBy;
    private List<String> realms;
    private long sizeBytes;
    private String status;              // COMPLETED, IN_PROGRESS, FAILED
    private String downloadUrl;         // relative URL for download

    public BackupMetadata() {
    }

    public String getBackupId() {
        return backupId;
    }

    public void setBackupId(String backupId) {
        this.backupId = backupId;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public long getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(long createdAt) {
        this.createdAt = createdAt;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(String createdBy) {
        this.createdBy = createdBy;
    }

    public List<String> getRealms() {
        return realms;
    }

    public void setRealms(List<String> realms) {
        this.realms = realms;
    }

    public long getSizeBytes() {
        return sizeBytes;
    }

    public void setSizeBytes(long sizeBytes) {
        this.sizeBytes = sizeBytes;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getDownloadUrl() {
        return downloadUrl;
    }

    public void setDownloadUrl(String downloadUrl) {
        this.downloadUrl = downloadUrl;
    }
}
